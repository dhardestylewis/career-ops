// Archetype detection
function detectArchetype(jobTitle, jobDesc) {
  const title = jobTitle.toLowerCase();
  const desc = (jobDesc || "").toLowerCase();
  const full = `${title} ${desc}`;

  if (
    full.includes("research") ||
    full.includes("scientist") ||
    full.includes("phd")
  ) {
    return "Research";
  }
  if (
    full.includes("forward deployed") ||
    full.includes("fde") ||
    full.includes("customer-facing") ||
    full.includes("solutions engineer")
  ) {
    return "FDE";
  }
  if (
    full.includes("infrastructure") ||
    full.includes("platform") ||
    full.includes("mlops") ||
    full.includes("serving")
  ) {
    return "Infrastructure";
  }
  if (
    full.includes("data scientist") ||
    full.includes("quantitative") ||
    full.includes("researcher")
  ) {
    return "Data Science";
  }
  return "Product ML";
}

// Parse salary from text
function parseSalary(text) {
  if (!text) return null;
  const match = text.match(/\$(\d+)k?(?:\s*-\s*\$)?(\d+)?k?/i);
  if (match) {
    const min = parseInt(match[1]);
    const max = match[2] ? parseInt(match[2]) : null;
    return max ? `$${min}K-$${max}K` : `$${min}K+`;
  }
  return null;
}

// Generate markdown report
function generateReport(roles) {
  let report = `# Daily Sourcing Report — ${TODAY}\n\n`;
  report += `**Auto-generated by sourcing-automation.mjs**\n\n`;

  report += `## New Postings Found (Last 24 Hours)\n\n`;

  if (roles.length === 0) {
    report += `No new postings found today.\n\n`;
  } else {
    report += `| Company | Role | Posted | Location | Comp | Archetype | Source | Action |\n`;
    report += `|---------|------|--------|----------|------|-----------|--------|--------|\n`;

    roles.forEach((role) => {
      report += `| ${role.company} | ${role.title} | ${role.posted} | ${role.location} | ${role.comp || "Not listed"} | ${role.archetype} | ${role.source} | Not applied |\n`;
    });

    report += `\n`;
  }

  // Summary stats
  report += `## Summary\n\n`;
  report += `- **Total found:** ${roles.length}\n`;

  const byComp = {
    target: roles.filter(
      (r) =>
        r.comp &&
        ((r.comp.includes("180") && r.comp.includes("220")) ||
          (r.comp.includes("200") && r.comp.includes("250")))
    ),
    stretch: roles.filter((r) => r.comp && r.comp.includes("250")),
    lower: roles.filter((r) => r.comp && r.comp.includes("150")),
  };

  report += `- **Target range ($180K-$250K):** ${byComp.target.length}\n`;
  report += `- **Stretch ($250K+):** ${byComp.stretch.length}\n`;
  report += `- **Lower (<$180K):** ${byComp.lower.length}\n`;

  const byArchetype = {
    Research: roles.filter((r) => r.archetype === "Research").length,
    Product: roles.filter((r) => r.archetype === "Product ML").length,
    FDE: roles.filter((r) => r.archetype === "FDE").length,
    Infrastructure: roles.filter((r) => r.archetype === "Infrastructure")
      .length,
    Other: roles.filter(
      (r) =>
        !["Research", "Product ML", "FDE", "Infrastructure"].includes(
          r.archetype
        )
    ).length,
  };

  report += `- **By archetype:** Research=${byArchetype.Research}, Product=${byArchetype.Product}, FDE=${byArchetype.FDE}, Infra=${byArchetype.Infrastructure}\n\n`;

  // High priority (estimated score 4.0+)
  const highPriority = roles.filter(
    (r) =>
      r.archetype === "Product ML" ||
      (r.archetype === "FDE" && r.comp && !r.comp.includes("150"))
  );

  report += `## High-Priority Roles (Est. Score 4.0+)\n\n`;
  if (highPriority.length === 0) {
    report += `None identified today.\n\n`;
  } else {
    highPriority.slice(0, 5).forEach((role, i) => {
      report += `${i + 1}. **${role.company}** — ${role.title}\n`;
      report += `   - ${role.archetype} | ${role.comp || "Comp TBD"} | ${role.posted}\n`;
    });
  }

  report += `\n## Next Steps\n\n`;
  report += `- [ ] Evaluate top 3 with \`/career-ops oferta\`\n`;
  report += `- [ ] Research contacts with \`/career-ops outreach-campaign\`\n`;
  report += `- [ ] Add to \`data/pipeline.md\` if score >4.0\n`;

  return report;
}

